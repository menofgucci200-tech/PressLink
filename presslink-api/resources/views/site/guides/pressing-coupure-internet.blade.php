    <p>Une coupure de réseau ou de courant ne doit pas arrêter votre comptoir : les clients continuent d'arriver avec leurs vêtements. Voici comment rester opérationnel, et ce qu'il faut attendre de votre logiciel.</p>

    <h2>Le problème des logiciels « tout en ligne »</h2>
    <p>Beaucoup d'outils en ligne cessent de fonctionner dès que la connexion tombe : impossible d'enregistrer un dépôt ou de retrouver une commande. Le personnel revient alors au cahier, et il faut tout ressaisir plus tard, avec des risques d'oubli et de doublons.</p>

    <h2>Ce qu'il faut pouvoir faire sans Internet</h2>
    <ul>
        <li>Enregistrer un nouveau client et une nouvelle commande.</li>
        <li>Encaisser un acompte ou un paiement.</li>
        <li>Faire avancer une commande et la remettre au client.</li>
        <li>Retrouver une commande récente pour répondre à un client.</li>
    </ul>

    <h2>Le retour de la connexion</h2>
    <p>Quand le réseau revient, tout ce qui a été fait hors connexion doit partir tout seul, une seule fois, sans rien ressaisir. Si une opération ne peut pas être appliquée (par exemple une commande déjà remise depuis un autre poste), le logiciel doit le signaler clairement plutôt que de l'ignorer.</p>

    <h2>Quelques bonnes habitudes</h2>
    <ul>
        <li>Gardez l'ordinateur ou la tablette du comptoir chargé, ou sur onduleur.</li>
        <li>Ouvrez votre logiciel une première fois chaque matin avec Internet, pour qu'il ait les données du jour.</li>
        <li>En cas de longue coupure, gardez un téléphone avec des données mobiles pour renvoyer les opérations dès que possible.</li>
    </ul>

