    <p>Dans un pressing, les vêtements prêts qui ne sont pas retirés occupent de la place, immobilisent votre argent quand le solde n'est pas encore payé, et finissent parfois oubliés. Le meilleur moyen de les faire partir : prévenir le client au bon moment, sans y passer la journée.</p>

    <h2>Les méthodes habituelles, et leurs limites</h2>
    <ul>
        <li><strong>L'appel téléphonique</strong> : efficace, mais long. Le client ne décroche pas toujours, et chaque appel coûte du crédit.</li>
        <li><strong>Le SMS</strong> : rapide, mais payant à chaque envoi et souvent noyé parmi les messages publicitaires.</li>
        <li><strong>Le message WhatsApp</strong> : apprécié des clients, mais il faut l'écrire à la main, commande par commande.</li>
        <li><strong>Rien du tout</strong> : le client revient « au hasard », souvent trop tôt, parfois beaucoup trop tard.</li>
    </ul>

    <h2>Ce que le client veut savoir</h2>
    <p>Un bon message tient en une ligne : <strong>votre commande est prête</strong>, avec son numéro, le <strong>reste à payer</strong> s'il y en a un, et si possible les horaires d'ouverture. Le client sait alors quand passer et prépare le bon montant.</p>

    <h2>Automatiser la notification</h2>
    <p>Le plus simple est que la notification parte toute seule, au moment où vous marquez la commande comme prête dans votre logiciel. Vous n'écrivez rien, vous ne composez aucun numéro, et aucun client n'est oublié.</p>

    <h2>Relancer les vêtements oubliés</h2>
    <p>Même prévenus, certains clients tardent. Repérez les commandes prêtes depuis plusieurs jours et relancez-les. Si vous appliquez des frais de garde au-delà d'un certain délai, annoncez-le clairement dès le dépôt, sur le reçu et dans vos conditions.</p>

    <h2>Avec PressLink</h2>
    <p>Quand vous marquez une commande « prête », le client reçoit automatiquement une notification dans l'application PressLink, gratuite pour lui, avec le reste à payer. Il suit aussi l'avancement de ses commandes à tout moment. Côté pressing, le tableau de bord signale les commandes prêtes depuis plusieurs jours à relancer. <a href="{{ route('site.clients') }}">Ce que voient vos clients</a>.</p>
